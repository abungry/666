function buildExtendedBeijingPlace(definition) {
    const [name, aliases, lat, lng, type, presetName, tags, desc, overrides = {}] = definition;
    const features = { ...BEIJING_PLACE_PRESETS[presetName], ...overrides };
    return {
        name,
        aliases: Array.from(new Set([name, ...aliases])),
        lat,
        lng,
        type,
        features,
        tags,
        desc,
        tips: [...BEIJING_PLACE_TIPS[presetName]]
    };
}

const existingBeijingPlaceNames = new Set(BEIJING_PLACES.map(place => place.name));
BEIJING_EXTRA_PLACE_DEFINITIONS
    .map(buildExtendedBeijingPlace)
    .filter(place => !existingBeijingPlaceNames.has(place.name))
    .forEach(place => {
        BEIJING_PLACES.push(place);
        existingBeijingPlaceNames.add(place.name);
    });
